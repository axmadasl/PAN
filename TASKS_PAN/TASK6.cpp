//==========================================
// Задача 6. Расчёт подъёмной силы на траектории
//==========================================

#include <iostream>
#include <iomanip>    
#include <clocale>

// Взяты как у «Самолёта А» из задачи 5
const double S = 30.0;   
const double CL = 0.6;    

double calculateLift(double rho, double V, double S, double CL)
{
    return 0.5 * rho * V * V * S * CL;
}

int main()
{
    setlocale(LC_ALL, "Russian");
    //==========================================================
    // Плотность взята из Международной стандартной атмосферы (МСА)
    // для высот 0, 1, 2, 3, 4, 5 км. Скорости — пример разгона
    // самолёта при наборе высоты.
    // =========================================================
    const int N = 6;                                                   // количество шагов
    double V[N] = { 60.0,  70.0,  80.0,  90.0,  100.0, 110.0 };      // скорость, м/с
    double rho[N] = { 1.225, 1.112, 1.007, 0.909, 0.819, 0.736 };      // плотность, кг/м^3
    //                0 км   1 км   2 км   3 км   4 км   5 км          // высота (для справки)

    std::cout << "=== Задача 6. Подъёмная сила на траектории ===\n";
    std::cout << "Параметры самолёта: S = " << S << " м^2, C_L = " << CL << "\n\n";

    std::cout << "+-----+---------------+-------------------+-------------------+\n";
    std::cout << "| Шаг | Скорость, м/с | Плотность, кг/м^3 | Подъёмная сила, Н |\n";
    std::cout << "+-----+---------------+-------------------+-------------------+\n";

    std::cout << std::fixed;   

    for (int i = 0; i < N; i++)
    {
        double L = calculateLift(rho[i], V[i], S, CL);

        std::cout << "| " << std::setw(3) << i + 1
            << " | " << std::setw(13) << std::setprecision(1) << V[i]
            << " | " << std::setw(17) << std::setprecision(3) << rho[i]
            << " | " << std::setw(17) << std::setprecision(1) << L
            << " |\n";
    }
    std::cout << "+-----+---------------+-------------------+-------------------+\n";

    return 0;
}